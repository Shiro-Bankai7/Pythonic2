create or replace function public.bootstrap_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id, username)
  values (new.id, 'learner_' || substring(new.id::text, 1, 8))
  on conflict (user_id) do nothing;

  insert into public.coin_wallet (user_id, balance)
  values (new.id, 100)
  on conflict (user_id) do nothing;

  insert into public.streaks (user_id, current_streak, freeze_count)
  values (new.id, 0, 0)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.bootstrap_new_user();

