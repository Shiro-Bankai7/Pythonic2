create or replace function public.get_user_dashboard()
returns table(
  streak integer,
  coins integer,
  total_xp bigint,
  weekly_xp bigint,
  lessons_completed bigint
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  perform public.ensure_user_rows(v_user_id);

  return query
  with xp as (
    select
      coalesce(sum(amount), 0)::bigint as total_xp,
      coalesce(sum(case when created_at >= now() - interval '7 days' then amount else 0 end), 0)::bigint as weekly_xp
    from public.xp_events
    where user_id = v_user_id
  ),
  progress as (
    select count(*)::bigint as lessons_completed
    from public.user_progress
    where user_id = v_user_id
  )
  select
    s.current_streak,
    cw.balance,
    xp.total_xp,
    xp.weekly_xp,
    progress.lessons_completed
  from public.streaks s
  join public.coin_wallet cw on cw.user_id = s.user_id
  cross join xp
  cross join progress
  where s.user_id = v_user_id;
end;
$$;

create or replace function public.complete_lesson_and_award(
  p_lesson_id text,
  p_track_id text,
  p_completed_at timestamptz default now(),
  p_is_daily_mission boolean default false
)
returns table(
  xp_awarded integer,
  coins_awarded integer,
  streak integer,
  coin_balance integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_day date := p_completed_at::date;
  v_last_day date;
  v_streak integer;
  v_freeze integer;
  v_first_completion_today boolean := false;
  v_new_streak integer;
  v_xp integer := 0;
  v_coins integer := 0;
  v_balance integer := 0;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  perform public.ensure_user_rows(v_user_id);

  insert into public.user_progress (user_id, lesson_id, track_id, completed_at)
  values (v_user_id, p_lesson_id, p_track_id, p_completed_at)
  on conflict (user_id, lesson_id) do nothing;

  begin
    insert into public.daily_activity (user_id, activity_date, did_complete)
    values (v_user_id, v_day, true);
    v_first_completion_today := true;
  exception
    when unique_violation then
      v_first_completion_today := false;
  end;

  select current_streak, last_completed_at::date, freeze_count
  into v_streak, v_last_day, v_freeze
  from public.streaks
  where user_id = v_user_id
  for update;

  if v_last_day is null then
    v_new_streak := 1;
  elsif v_day = v_last_day then
    v_new_streak := v_streak;
  elsif v_day - v_last_day <= 2 then
    v_new_streak := v_streak + 1;
  elsif v_freeze > 0 then
    v_new_streak := v_streak + 1;
    v_freeze := v_freeze - 1;
  else
    v_new_streak := 1;
  end if;

  update public.streaks
  set
    current_streak = v_new_streak,
    last_completed_at = p_completed_at,
    freeze_count = v_freeze,
    updated_at = now()
  where user_id = v_user_id;

  if v_first_completion_today then
    v_xp := v_xp + 25;
    v_coins := v_coins + 10;

    if p_is_daily_mission then
      v_xp := v_xp + 20;
      v_coins := v_coins + 15;
    end if;

    if v_new_streak > 0 and v_new_streak % 7 = 0 then
      v_xp := v_xp + 30;
      v_coins := v_coins + 20;
    end if;
  end if;

  if v_xp > 0 then
    insert into public.xp_events (user_id, type, amount, meta)
    values (
      v_user_id,
      case when p_is_daily_mission then 'daily_mission_completion' else 'lesson_completion' end,
      v_xp,
      jsonb_build_object('lesson_id', p_lesson_id, 'track_id', p_track_id)
    );
  end if;

  if v_coins <> 0 then
    insert into public.coin_events (user_id, amount, reason, meta)
    values (
      v_user_id,
      v_coins,
      case when p_is_daily_mission then 'daily_mission_reward' else 'lesson_reward' end,
      jsonb_build_object('lesson_id', p_lesson_id, 'track_id', p_track_id)
    );

    update public.coin_wallet
    set balance = balance + v_coins, updated_at = now()
    where user_id = v_user_id
    returning balance into v_balance;
  else
    select balance into v_balance from public.coin_wallet where user_id = v_user_id;
  end if;

  return query
  select v_xp, v_coins, v_new_streak, v_balance;
end;
$$;

create or replace function public.purchase_hint_tier(
  p_lesson_id text,
  p_tier text,
  p_cost integer
)
returns table(coin_balance integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_balance integer;
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  if p_tier not in ('hint1', 'hint2', 'full') then
    raise exception 'Invalid hint tier';
  end if;

  perform public.ensure_user_rows(v_user_id);

  select balance into v_balance
  from public.coin_wallet
  where user_id = v_user_id
  for update;

  if v_balance < p_cost then
    raise exception 'Insufficient coins';
  end if;

  update public.coin_wallet
  set balance = balance - p_cost, updated_at = now()
  where user_id = v_user_id
  returning balance into v_balance;

  insert into public.coin_events (user_id, amount, reason, meta)
  values (v_user_id, -p_cost, 'hint_purchase', jsonb_build_object('lesson_id', p_lesson_id, 'tier', p_tier));

  insert into public.hint_purchases (user_id, lesson_id, tier, cost)
  values (v_user_id, p_lesson_id, p_tier, p_cost);

  return query select v_balance;
end;
$$;

