-- Pythonic core schema for auth-backed progression, rewards, and leaderboards.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null default ('learner_' || substring(gen_random_uuid()::text, 1, 8)),
  avatar text,
  created_at timestamptz not null default now()
);

create table if not exists public.user_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id text not null,
  track_id text not null,
  completed_at timestamptz not null default now(),
  unique (user_id, lesson_id)
);

create table if not exists public.daily_activity (
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_date date not null,
  did_complete boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (user_id, activity_date)
);

create table if not exists public.streaks (
  user_id uuid primary key references auth.users(id) on delete cascade,
  current_streak integer not null default 0,
  last_completed_at timestamptz,
  freeze_count integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.xp_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  amount integer not null,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.coin_wallet (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.coin_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount integer not null,
  reason text not null,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.hint_purchases (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id text not null,
  tier text not null check (tier in ('hint1', 'hint2', 'full')),
  cost integer not null check (cost >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id text not null,
  code_hash text not null,
  verdict text not null check (verdict in ('PASS', 'FAIL')),
  feedback_json jsonb not null default '{}'::jsonb,
  estimated_tokens integer,
  estimated_cost_usd numeric(10, 6),
  created_at timestamptz not null default now()
);

create table if not exists public.groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  join_code text not null unique,
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid not null references public.groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (group_id, user_id)
);

create table if not exists public.user_badges (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  badge text not null,
  created_at timestamptz not null default now(),
  unique (user_id, badge)
);

create index if not exists idx_user_progress_user_id on public.user_progress(user_id);
create index if not exists idx_daily_activity_user_id on public.daily_activity(user_id);
create index if not exists idx_xp_events_user_id on public.xp_events(user_id);
create index if not exists idx_coin_events_user_id on public.coin_events(user_id);
create index if not exists idx_hint_purchases_user_id on public.hint_purchases(user_id);
create index if not exists idx_attempts_user_id on public.attempts(user_id);
create index if not exists idx_group_members_user_id on public.group_members(user_id);

